/* ===========================================================
   THE GIFT UNASKED — the manuscript
   Edit the text between the backticks. Rules:
     THE POET / THE THEOLOGIAN   on their own line start a speech.
     blank line                  separates stanzas.
     @4                          starts chapter 4 at the next speech.
     >>ask                       adds a "you may answer first" pause before the next speech.
     ~stanza                     emphasis (italic, longer breath).
     !stanza                     the stanza stands alone on screen first.
   Markers are stripped on display; the words are never altered.
   =========================================================== */
window.GU = window.GU || {};
GU.chapters = [
  'THE GIFT', 'THE UNASKED LIFE', 'THE FALL', 'THE PRICE OF FREEDOM',
  'THE BOOK', 'THE HAND OF MAN', 'THE PROBLEM OF BELIEF', 'REVELATION',
  'HEAVEN', 'THE QUESTION OF SUFFERING', 'THE FINAL OBJECTION', 'THE SILENCE'
];

GU.manuscript = `
@1
THE POET

Tell me, then, Doctor of the sacred page,
Before your God had breathed the world to age,
What was I?

~Nothing?

No hunger.
No grief.
No hope misplaced.
No child beneath a famine's sky,
No mother burying what she prayed would live,
No sinner trembling underneath a heaven
He never begged to enter.

Nothing.

And yet you call existence gift.

!What gift is this,
whose recipient was not there to ask?

THE THEOLOGIAN

Because to exist is better than not to be.
The world contains suffering, yes,
but also love, beauty, knowledge, friendship,
the sunrise over water,
the hand that finds another hand in darkness.
Creation is not merely pain.

Genesis says God saw what He had made
and called it good.

THE POET

You have answered what existence contains,
not why existence was imposed.

You say the world is good
because I can find roses among its graves.

But did the rose consent to the thorn?

Did the child consent to the famine?

Did the man born into misery
receive some heavenly ballot
upon which he marked,

“Yes, I accept this life,
with all its terms and consequences”?

THE THEOLOGIAN

No.

No one consents to being born.

@2
THE POET

Then why call refusal rebellion?

You say:

“Choose God.”

But when did I choose to enter the room?

You say:

“Obey.”

But who appointed the law
before the accused was born?

You say:

“Believe, or perish.”

But who placed belief beyond certainty
and punishment beyond death?

And then, most curious of all,

you say I am saved.

~Saved?

!From what?

>>ask
THE THEOLOGIAN

From sin.

From death.

From separation from God.

From the consequence of the Fall.

@3
THE POET

The Fall.

There is the ancient hinge.

Adam eats.

I inherit.

A serpent whispers.

I receive the sentence.

Tell me, Doctor:

If a father commits the crime,
why does the child inherit the prison?

THE THEOLOGIAN

Christian traditions differ.

Some understand humanity as inheriting a fallen nature,
not Adam's personal guilt.

Others emphasise that humanity participates
in the same rebellion.

Paul says that through one man
sin entered the world.

THE POET

Then Paul gives me another question.

If God knew Adam would fall
before God made Adam,

then the Fall was not a surprise.

And if the Fall was foreknown,
then the world of sin was foreseen.

And if suffering was foreseen,

then every starving infant,
every betrayed lover,
every frightened prisoner,
every person crushed beneath history

was already visible
before the first atom stirred.

So tell me plainly:

Was the suffering unforeseen?

THE THEOLOGIAN

No.

THE POET

Was it unavoidable?

THE THEOLOGIAN

Not necessarily.

THE POET

Then God knew it could happen.

THE THEOLOGIAN

Yes.

THE POET

And created anyway.

THE THEOLOGIAN

Yes.

@4
THE POET

Then my question remains.

!Why?

THE THEOLOGIAN

Christian theology answers that God desired creatures capable of genuine love.

Love requires freedom.

A creature programmed only to worship
would perform obedience,
but not freely love.

THE POET

Then your God chose freedom
knowing freedom would produce rebellion.

THE THEOLOGIAN

Yes.

THE POET

Then freedom is permitted,

until I use it against Him.

And when I exercise the very freedom
He valued enough to create,

He may punish me eternally.

!What kind of freedom is that?

THE THEOLOGIAN

Christian theology does not necessarily teach
that every disagreement with God is punished eternally.

There are different doctrines of hell:
eternal conscious punishment, annihilationism,
and universal reconciliation.

But Scripture certainly contains severe warnings
about judgment.

THE POET

Then let us not soften the page.

Revelation speaks of judgment.

It speaks of the lake of fire.

It speaks of death and Hades
cast into that fire.

It speaks of those whose names
are not found in the book of life.

Why?

If freedom is sacred,

why does freedom have an abyss beneath it?

>>ask
THE THEOLOGIAN

Because freedom has consequences.

THE POET

Then consequence is not freedom's enemy.

But infinite consequence for finite decisions?

That is another matter.

A life lasts decades.

A choice lasts seconds.

A punishment lasts forever.

!Explain the proportion.

THE THEOLOGIAN

That is one of the deepest disputes within theology.

Some Christians argue that rejecting God
is not merely breaking a rule
but rejecting the source of life itself.

Others reject eternal conscious torment
precisely because they believe everlasting punishment
would be incompatible with God's justice.

THE POET

So even your theologians disagree
about what justice means.

THE THEOLOGIAN

Yes.

@5
THE POET

Then perhaps the mystery is not that man doubts God.

Perhaps the mystery is that God gave man a book
so capable of generating doubt.

THE THEOLOGIAN

Or perhaps He gave humanity a book
that demands interpretation.

THE POET

Then why does revelation require archaeology,
ancient languages, historical context,
manuscript comparison,
and centuries of argument
to tell me what my creator wants?

If the message concerns eternity,

!why not write it in the stars?

THE THEOLOGIAN

Perhaps revelation was never intended
to be a scientific textbook.

Genesis speaks through the conceptual world
of the ancient Near East.

Its purpose is theological:

Who created?

Why does creation matter?

What is humanity?

Why is there evil?

Why are we alienated from God?

THE POET

Then why does Genesis speak of a firmament?

Why describe waters above
and waters below?

Why speak of the sun and moon
as the great lights?

Why does the universe appear
through the eyes of an ancient observer?

If God stood beyond the heavens,

why does His book sometimes sound
as though it stands beneath them?

THE THEOLOGIAN

Because revelation may be accommodated
to human understanding.

THE POET

Accommodation.

A beautiful word.

But does it mean God speaks truth
in a language His children can understand,

or that men spoke about God
using the knowledge available to them?

THE THEOLOGIAN

That distinction is difficult.

THE POET

And there is another.

Genesis has two creation accounts
that many scholars understand as distinct traditions.

One gives humanity after the animals.

Another tells of Adam,
then the animals,
then Eve.

Why?

THE THEOLOGIAN

Because the Bible is a library,
not a single document written in one sitting.

Different books possess different authors,
genres, purposes, and historical settings.

Christian theology can regard Scripture as inspired
without requiring every passage
to function like a modern scientific report.

THE POET

Then inspiration does not mean dictation.

THE THEOLOGIAN

Not necessarily.

@6
THE POET

Then the hand of man is inside the book.

THE THEOLOGIAN

Yes.

THE POET

Then let us speak of that hand.

Why does that hand sometimes write:

“Love your neighbour,”

yet elsewhere permit slavery?

Why does it proclaim mercy,

yet contain wars, conquest,
and commands of destruction?

Why does Paul tell women to be silent
in one passage,

and elsewhere acknowledge women
who worked alongside him?

Why does Genesis describe woman
as created from man,

while the same Scriptures also proclaim
that male and female bear God's image?

Why does Paul speak of submission
and yet declare that in Christ
there is neither male nor female?

THE THEOLOGIAN

Because the Bible contains different voices
within different historical circumstances.

Some passages have been interpreted
as universal commands.

Others reflect ancient social structures.

Christians disagree sharply
over which is which.

THE POET

Then morality did not become obvious
simply because the ink was holy.

Men still had to interpret it.

THE THEOLOGIAN

Yes.

THE POET

Then how do you know
the interpretation you call God's will
is not simply the age speaking through God?

THE THEOLOGIAN

You do not know merely by confidence.

You examine context, language, genre,
historical setting, the whole canon,
and the central Christian claim
that Jesus reveals God's character.

THE POET

So the Bible must be interpreted through a person
to understand the Bible.

THE THEOLOGIAN

That is one Christian approach.

THE POET

Curious.

A book supposedly written for humanity
requires humanity to explain it.

And humanity disagrees.

Catholic.

Orthodox.

Protestant.

Calvinist.

Arminian.

Universalist.

Annihilationist.

Literalist.

Allegorist.

All opening the same book
and finding different eternities.

THE THEOLOGIAN

Interpretation does not prove the text false.

THE POET

No.

But neither does disagreement prove it true.

THE THEOLOGIAN

Fair.

@7
THE POET

Then let us return to heaven.

Suppose I live honestly.

I love people.

I seek truth.

I do not steal.

I do not murder.

I help the suffering.

But I cannot honestly say,

“I believe.”

Not because I hate God,

but because I cannot manufacture certainty.

Would an all-knowing God not know
that my disbelief was sincere?

THE THEOLOGIAN

If God is omniscient,
then yes, He would know the difference
between deliberate rejection
and honest uncertainty.

Christian thinkers disagree
about the fate of those
who never come to faith.

THE POET

Again uncertainty.

Yet the stakes are eternity.

How strange.

The question is enormous,

but the answer is divided.

THE THEOLOGIAN

Faith has never been presented
as mathematical certainty.

THE POET

Then why threaten uncertainty
with eternal certainty?

THE THEOLOGIAN

That is a powerful objection.

@8
THE POET

And Revelation.

Let us go there.

Not gently.

At the end of the Bible,

the dead rise.

Judgment comes.

Books are opened.

Names are examined.

Death itself is destroyed.

Then there is a new heaven
and a new earth.

And God's servants serve Him.

Forever.

Tell me:

What does an immortal creature do
after ten million years of worship?

After ten billion?

After numbers lose meaning?

THE THEOLOGIAN

Revelation portrays eternal life
as communion with God,
not merely monotonous singing.

The image is symbolic and expansive.

It includes a renewed creation,
the end of death,
the end of mourning,
and God's presence with humanity.

THE POET

Then perhaps heaven is not an eternal choir.

THE THEOLOGIAN

Not necessarily.

THE POET

Then why does the image of worship dominate?

THE THEOLOGIAN

Because worship, in biblical thought,
means more than singing.

It means recognising what is ultimate.

@9
THE POET

But if I cannot leave,

is devotion still devotion?

If there is nowhere else to go,

is loyalty freely chosen?

If rebellion is impossible,

is obedience virtue?

If every creature eventually bows,

what becomes of freedom?

THE THEOLOGIAN

Perhaps heaven perfects freedom
rather than removes it.

THE POET

Then freedom is perfected
when I no longer desire to leave.

THE THEOLOGIAN

That is one theological answer.

@10
THE POET

And another question appears.

If God can create creatures
who freely love Him in heaven,

why could He not create creatures
who freely love Him from the beginning?

Why the garden?

Why the serpent?

Why the Fall?

Why the cross?

Why the grave?

Why the judgement?

Why the long road,

if the destination could exist
without the catastrophe?

THE THEOLOGIAN

Because perhaps a relationship
cannot simply be programmed into existence.

Perhaps love requires becoming.

Perhaps freedom requires the possibility
of rejection.

Perhaps redemption reveals something
creation alone could not reveal.

THE POET

Then suffering becomes part of the lesson.

THE THEOLOGIAN

Some theologians would say
God can bring good from suffering.

THE POET

Bring good from it.

But why permit it at all?

A surgeon may heal a wound,

but he does not deserve praise
for creating the wound
unless the wound was necessary.

!Was it necessary?

THE THEOLOGIAN

I cannot honestly say
that every suffering is necessary.

THE POET

Then neither can theology
justify every tear.

THE THEOLOGIAN

No.

THE POET

Then perhaps faith is not an answer.

Perhaps faith is the courage
to remain beside the unanswered question.

THE THEOLOGIAN

Perhaps.

@11
THE POET

But I have one final objection.

You say existence is grace.

You say God gave me consciousness.

Then you say I owe Him gratitude.

You say I owe Him worship.

You say I owe Him obedience.

You say I must live according to His boundaries.

You say my choices matter eternally.

And when I ask,

!“Who asked for this?”

you call me ungrateful.

~Ungrateful?

For what?

For the gift of a life
I did not request?

For rules I did not write?

For a fall I did not commit?

For suffering I did not choose?

For judgment I did not design?

For salvation from a condition
I never volunteered to enter?

THE THEOLOGIAN

Perhaps gratitude cannot be demanded.

Perhaps it must arise freely.

THE POET

Then we agree.

THE THEOLOGIAN

On that, perhaps.

THE POET

And if God exists?

THE THEOLOGIAN

Then these questions still matter.

THE POET

Even to God?

THE THEOLOGIAN

Especially to God.

@12
THE POET

Then let Him answer.

>>ask
THE THEOLOGIAN

Perhaps He already has.

THE POET

Where?

THE THEOLOGIAN

!In the silence.

THE POET

Then silence is a strange scripture.

THE THEOLOGIAN

~And yet you are still reading.

THE POET

Yes.

Because perhaps my doubt
is not the opposite of faith.

Perhaps it is faith
refusing to lie to itself.

And perhaps somewhere beyond
this little human theatre,

beyond Genesis,
beyond Revelation,
beyond the stars as men once imagined them,

there is an answer.

But until then,

I will ask.

Not because I hate the heavens.

Not because I worship the void.

Not because I have proved God absent.

But because if God made me capable of reason,

then surely He knew

I would eventually look toward the heavens
and ask the most dangerous question
a creature can ask its creator:

!Why did You make me at all?

And if the answer is,

“Because I love you,”

then I shall ask again:

Why was love not possible
without first making me capable of pain?

And if He says,

“Because I gave you freedom,”

I shall ask:

Why create a freedom
whose honest exercise can condemn me?

And if He says,

“Because salvation awaits you,”

I shall ask:

Why must I be saved
from a world You knew I would enter?

And if He says,

“Because eternity is a gift,”

I shall ask:

Why is oblivion so terrible
that I must be grateful
not to have remained there?

And if Heaven opens,

and every voice rises,

and every knee bends,

and every tongue confesses,

I shall look upon the endless throne
and whisper, not in hatred,

but in wonder:

!I did not ask to be.

Then perhaps the oldest question
will finally meet its oldest answer.

Or perhaps,

after all the stars have burned,

after every book has closed,

after every theologian has surrendered
his final argument,

the universe will simply remain silent.

And I,

who was once nothing,

will have spent my brief existence
asking why I became something.

THE THEOLOGIAN

And perhaps that question itself
was one of the reasons
you were made.

THE POET

Then God has made a curious creature.

He gave it life,

gave it doubt,

gave it reason,

gave it freedom,

and then watched it turn
all four against the mystery.

THE THEOLOGIAN

Perhaps.

THE POET

Then let the mystery remain.

But do not call my question ingratitude.

For if I was truly made free,

then surely,

the first freedom I possess

is the freedom

to ask why I was made.

And if no answer comes,

let the question stand—not as a wound closed over,
but as a small flame carried through the dark.

Let it burn in the hands of every creature
who wakes beneath an unchosen sky,
who loves despite the cost,
who suffers without explanation,
who reaches toward the silence
and finds, for one trembling moment,
that the silence has become a mirror.

There, at the edge of being,

I will not kneel merely because I was made.

I will not curse the life that wounded me.

I will hold it up like a candle
before whatever waits beyond the dark—

not as proof,

not as surrender,

but as testimony:

I was here.

I felt the weight of existence.

I questioned the hand that gave it.

And still,

for one brief and impossible moment,

I chose what to do with the light.
`;

/* ---------- parser ---------- */
GU.parse = function (raw) {
  const turns = [];
  let cur = null, ch = 1, ask = false, chNew = false;
  raw.split('\n').forEach(function (line) {
    const l = line.replace(/\s+$/, '');
    let m;
    if ((m = /^@(\d+)$/.exec(l))) { ch = +m[1]; chNew = true; return; }
    if (l === '>>ask') { ask = true; return; }
    if (l === 'THE POET' || l === 'THE THEOLOGIAN') {
      cur = { sp: l === 'THE POET' ? 'poet' : 'theo', ch: ch, ask: ask, chStart: chNew, lines: [] };
      turns.push(cur); ask = false; chNew = false; return;
    }
    if (cur) cur.lines.push(l);
  });
  turns.forEach(function (t) {
    t.stanzas = t.lines.join('\n').trim().split(/\n[ \t]*\n+/).map(function (s) {
      s = s.trim();
      const f = /^([~!])/.exec(s);
      return { flag: f ? f[1] : '', text: f ? s.slice(1) : s };
    });
    delete t.lines;
  });
  return turns;
};
GU.turns = GU.parse(GU.manuscript);
GU.firstTurnOfChapter = function (c) {
  for (let i = 0; i < GU.turns.length; i++) if (GU.turns[i].ch === c) return i;
  return 0;
};
